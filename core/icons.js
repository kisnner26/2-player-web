/** Devuelve el SVG (como string) del icono `name`. */
export function icon(name, { size = 18, cls = '' } = {}) {
  const d = PATHS[name] || PATHS.target;
  return `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none"
            stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"
            aria-hidden="true"><path d="${d}"/></svg>`;
}

/** Envuelve un icono + etiqueta, para botones. */
export function iconLabel(name, label, opts = {}) {
  return `${icon(name, opts)}<span>${label}</span>`;
}

